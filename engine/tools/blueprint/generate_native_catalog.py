#!/usr/bin/env python3
"""Project the script-reference catalogue into a small, dependency-free C++ table."""
import argparse
import json
from pathlib import Path

here = Path(__file__).resolve().parent
source = (here / "catalog.js").read_text(encoding="utf-8")
nodes = json.loads(source.split("const catalog=", 1)[1].split(";if(typeof module", 1)[0])["nodes"]
def pins(items):
    return "|".join(p["name"] + ":" + p["type"] for p in items)
lines = ["// Generated by generate_native_catalog.py; do not edit.\n"]
for n in nodes:
    ins = ([] if n["pure"] else [{"name":"in","type":"exec"}]) + n["inputs"]
    outs = ([] if n["pure"] else [{"name":"then","type":"exec"}]) + n["outputs"]
    if n["result"] != "void":
        outs += [{"name":"result","type":n["result"]}]
    row = [n["id"], n["title"], n["category"], pins(ins), pins(outs)]
    lines.append("    {" + ", ".join(json.dumps(s, ensure_ascii=True) for s in row) + "},\n")
target = here / "native_catalog.inc"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
generated = "".join(lines)
if args.check:
    if not target.exists() or target.read_text(encoding="utf-8") != generated:
        parser.exit(1, "Native catalogue is stale. Run generate_native_catalog.py.\n")
else:
    target.write_text(generated, encoding="utf-8")
print(f"{len(nodes)} native API nodes")
