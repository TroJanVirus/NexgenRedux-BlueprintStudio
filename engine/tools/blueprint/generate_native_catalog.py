#!/usr/bin/env python3
"""Project the script-reference catalogue into a small, dependency-free C++ table."""
import argparse
import json
from pathlib import Path

here = Path(__file__).resolve().parent
source = (here / "catalog.js").read_text(encoding="utf-8")
catalog = json.loads(source.split("const catalog=", 1)[1].split(";if(typeof module", 1)[0])
nodes = catalog["nodes"]
def pins(items):
    return "|".join(p["name"] + ":" + p["type"] for p in items)
def default_expr(p):
    value = p["default"]
    def scalar(v):
        return format(v, ".15g")
    if p["type"] in ("int64","uint64"):
        return p["type"] + "(" + str(int(value)) + ")"
    if p["type"] == "string":
        return json.dumps(value, ensure_ascii=True)
    if isinstance(value, list):
        return p["type"] + "(" + ", ".join(scalar(v) for v in value) + ")"
    if isinstance(value, bool):
        return str(value).lower()
    if isinstance(value, (int, float)):
        return p["type"] + "(" + scalar(value) + ")"
    if isinstance(value, str) and value.isascii() and value.isidentifier():
        return value
    raise ValueError("Unsupported API default: " + repr(p))
lines = ["// Generated by generate_native_catalog.py; do not edit.\n"]
for n in nodes:
    ins = ([] if n["pure"] else [{"name":"in","type":"exec"}]) + n["inputs"]
    outs = ([] if n["pure"] else [{"name":"then","type":"exec"}]) + n["outputs"]
    if n["result"] != "void":
        outs += [{"name":"result","type":n["result"]}]
    row = [n["id"], n["title"], n["category"], pins(ins), pins(outs), n["call"], n["property"], "member" if n["member"] else "", "pure" if n["pure"] else "", n["result"], "out" if n["outputs"] else "", "|".join(("out:" if p["out"] else "in:") + p["name"] for p in n["arguments"]), "|".join(p["name"] + ":" + default_expr(p) for p in n["inputs"] if "default" in p)]
    lines.append("    {" + ", ".join(json.dumps(s, ensure_ascii=True) for s in row) + "},\n")
target = here / "native_catalog.inc"
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
generated = "".join(lines)
if args.check:
    if not target.exists() or target.read_text(encoding="utf-8") != generated:
        parser.exit(1, "Native catalogue is stale. Run generate_native_catalog.py.\n")
else:
    target.write_text(generated, encoding="utf-8")
enum_target = here / "native_enums.inc"
enum_generated = "// Generated by generate_native_catalog.py; do not edit.\n" + "".join(
    "    {" + json.dumps(name) + ", " + json.dumps(value) + "},\n"
    for name, values in sorted(catalog["enums"].items()) for value in values)
if args.check:
    if not enum_target.exists() or enum_target.read_text(encoding="utf-8") != enum_generated:
        parser.exit(1, "Native enum catalogue is stale. Run generate_native_catalog.py.\n")
else:
    enum_target.write_text(enum_generated, encoding="utf-8")
print(f"{len(nodes)} native API nodes; {len(catalog['enums'])} enum types")
